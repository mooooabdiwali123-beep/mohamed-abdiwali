create extension if not exists pgcrypto;

create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 email text,
 role text not null default 'staff' check (role in ('owner','manager','receptionist','housekeeping','staff')),
 created_at timestamptz not null default now()
);

create table if not exists public.rooms (
 id bigint generated by default as identity primary key,
 room_number text not null unique,
 room_type text not null default 'Standard',
 price_per_night numeric(12,2) not null default 0 check (price_per_night >= 0),
 status text not null default 'available' check (status in ('available','occupied','cleaning','maintenance')),
 created_at timestamptz not null default now()
);

create table if not exists public.bookings (
 id uuid primary key default gen_random_uuid(),
 guest_name text not null,
 guest_phone text,
 room_id bigint not null references public.rooms(id),
 check_in date not null,
 check_out date not null,
 total_amount numeric(12,2) not null default 0 check (total_amount >= 0),
 payment_status text not null default 'unpaid' check (payment_status in ('unpaid','partial','paid')),
 status text not null default 'confirmed' check (status in ('confirmed','checked_in','checked_out','cancelled')),
 created_by uuid references auth.users(id),
 created_at timestamptz not null default now(),
 constraint valid_stay_dates check (check_out > check_in)
);

create table if not exists public.payments (
 id uuid primary key default gen_random_uuid(),
 booking_id uuid not null references public.bookings(id) on delete cascade,
 amount numeric(12,2) not null check (amount > 0),
 method text not null default 'cash' check (method in ('cash','card','mobile_money','bank_transfer')),
 received_by uuid references auth.users(id),
 received_at timestamptz not null default now(),
 note text
);

create index if not exists bookings_room_dates_idx on public.bookings(room_id,check_in,check_out);
create index if not exists bookings_created_at_idx on public.bookings(created_at desc);
create index if not exists payments_booking_idx on public.payments(booking_id);

alter table public.profiles enable row level security;
alter table public.rooms enable row level security;
alter table public.bookings enable row level security;
alter table public.payments enable row level security;

-- Signed-in staff can access operational records. For a production hotel,
-- tighten policies by role and add server-side booking overlap checks.
drop policy if exists "signed in read profiles" on public.profiles;
create policy "signed in read profiles" on public.profiles for select to authenticated using (true);
drop policy if exists "users insert own profile" on public.profiles;
create policy "users insert own profile" on public.profiles for insert to authenticated with check (auth.uid() = id);
drop policy if exists "users update own profile" on public.profiles;
create policy "users update own profile" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "staff read rooms" on public.rooms;
create policy "staff read rooms" on public.rooms for select to authenticated using (true);
drop policy if exists "staff add rooms" on public.rooms;
create policy "staff add rooms" on public.rooms for insert to authenticated with check (true);
drop policy if exists "staff update rooms" on public.rooms;
create policy "staff update rooms" on public.rooms for update to authenticated using (true) with check (true);

drop policy if exists "staff read bookings" on public.bookings;
create policy "staff read bookings" on public.bookings for select to authenticated using (true);
drop policy if exists "staff add bookings" on public.bookings;
create policy "staff add bookings" on public.bookings for insert to authenticated with check (auth.uid() = created_by);
drop policy if exists "staff update bookings" on public.bookings;
create policy "staff update bookings" on public.bookings for update to authenticated using (true) with check (true);

drop policy if exists "staff read payments" on public.payments;
create policy "staff read payments" on public.payments for select to authenticated using (true);
drop policy if exists "staff add payments" on public.payments;
create policy "staff add payments" on public.payments for insert to authenticated with check (auth.uid() = received_by);

-- Create a profile row for every new Supabase Auth user.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
 insert into public.profiles (id,email,role) values (new.id,new.email,'staff')
 on conflict (id) do update set email=excluded.email;
 return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

